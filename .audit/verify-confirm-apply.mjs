import { browser, login, sqlJson, shot } from './harness.mjs'
const b = await browser()
for (const id of ['RTS-10052','RTS-10041']) {
  console.log(`── ${id} before:`, JSON.stringify((await sqlJson(`select status, eta, workflow->>'confirmed' confirmed, workflow->>'invoiceAmount' amt from orders where id='${id}'`))[0]))
  const { page, ctx, errors } = await login(b, 'rajni')
  await page.waitForTimeout(1200)
  await page.goto(`http://127.0.0.1:5173/admin/orders/${id}`, { waitUntil: 'domcontentloaded' })
  await page.waitForTimeout(2500)
  await page.getByRole('button', { name: /price/i }).first().click()
  await page.waitForTimeout(800)
  await page.getByRole('button', { name: /^(Confirm order|Save price & date)$/ }).first().click()
  await page.waitForTimeout(3500)
  console.log(`   after:`, JSON.stringify((await sqlJson(`select status, eta, workflow->>'confirmed' confirmed, workflow->>'invoiceAmount' amt, workflow->>'confirmedBy' by from orders where id='${id}'`))[0]))
  console.log(`   client message:`, JSON.stringify((await sqlJson(`select body from support_messages where order_id='${id}' order by created_at desc limit 1`))[0]?.body || '(none)'))
  const t = await page.locator('body').innerText()
  console.log(`   banner:`, /Not saved/i.test(t) ? '*** Not saved' : 'none ✓')
  await shot(page, `applied-${id}`)
  const pe = errors.filter(e => e.startsWith('PAGEERROR')); if (pe.length) console.log('   PAGE ERRORS:', pe.slice(0,2))
  await ctx.close()
}
await b.close()
